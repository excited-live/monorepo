/**
 * Rewrites the Better Auth schema block inside apps/api/migrations/0001_init.sql.
 *
 * Why a generated block inside the ledger: `apps/api` owns one
 * wrangler-standard migration ledger (apps/api/migrations/*.sql mirrored into
 * migrations.generated.ts and applied at boot on D1 and node:sqlite). Better
 * Auth's own programmatic migrator would be a second, parallel path, so
 * instead we dump the exact DDL the installed better-auth version expects
 * into the merged baseline migration, between the
 * `-- BEGIN BETTER AUTH SCHEMA` / `-- END BETTER AUTH SCHEMA` markers.
 *
 * Run: pnpm --filter @excited-live/auth gen:schema
 * Then: pnpm --filter @excited-live/api gen:migrations
 *
 * The dump compiles against an empty database with every plugin from the
 * `both` mount enabled, so all tables (core + apiKey + oauth provider) land
 * in the block. Re-run whenever better-auth or a plugin bumps its schema.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { DatabaseSync } from "node:sqlite"
import { getMigrations } from "better-auth/db/migration"
import { NodeSqliteDialect } from "@better-auth/kysely-adapter/node-sqlite-dialect"
import { bearer, jwt } from "better-auth/plugins"
import { apiKey } from "@better-auth/api-key"
import { oauthProvider } from "@better-auth/oauth-provider"

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..")
const repoDir = join(packageDir, "..", "..")
const ledgerPath = join(repoDir, "apps", "api", "migrations", "0001_init.sql")

const BEGIN_MARKER = "-- BEGIN BETTER AUTH SCHEMA"
const END_MARKER = "-- END BETTER AUTH SCHEMA"

const config = {
	appName: "excited-live",
	secret: "gen-schema-placeholder-not-a-secret",
	baseURL: "http://localhost:3000",
	emailAndPassword: { enabled: true },
	database: {
		dialect: new NodeSqliteDialect({ database: new DatabaseSync(":memory:") }),
		type: "sqlite" as const,
		transaction: false,
	},
	plugins: [bearer(), apiKey(), jwt(), oauthProvider({ loginPage: "/sign-in" })],
}

const migrations = await getMigrations(config as never, { throwOnUnsafe: false })
const ddl = await migrations.compileMigrations()

const statements = ddl
	.split(";")
	.map((statement) => statement.trim())
	.filter((statement) => statement.length > 0)

if (statements.length === 0) {
	console.error("compileMigrations returned no statements — better-auth version changed?")
	process.exit(1)
}

const tables = statements.filter((statement) => /create table/i.test(statement)).length
const indexes = statements.filter((statement) => /create (unique )?index/i.test(statement)).length

const header = [
	`${BEGIN_MARKER} (generated by packages/auth — do not edit;`,
	"-- regenerate with pnpm --filter @excited-live/auth gen:schema, then re-mirror",
	"-- with pnpm --filter @excited-live/api gen:migrations). Better Auth +",
	"-- apiKey + oauthProvider DDL of the installed versions. Same ledger rules:",
	"-- one statement per `;` on its own line, no triggers or string literals",
	"-- containing `;`.",
]

const body = statements.map((sql) => `${sql};\n`).join("\n")
const block = `${header.join("\n")}\n\n${body}${END_MARKER}\n`

const ledger = readFileSync(ledgerPath, "utf8")
const blockPattern = new RegExp(`${BEGIN_MARKER.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END_MARKER.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\n`)
if (!blockPattern.test(ledger)) {
	console.error(`Markers "${BEGIN_MARKER}" / "${END_MARKER}" not found in ${ledgerPath}`)
	process.exit(1)
}

writeFileSync(ledgerPath, ledger.replace(blockPattern, block))

console.log(
	`Rewrote the auth block in ${ledgerPath}: ${statements.length} statement(s) — ${tables} table(s), ${indexes} index(es).`,
)
